/*
 * P1449 后缀表达式
 * 难度：一般
 * 关键点：栈，字符串处理
 * 核心思路：
 *   读入整个表达式字符串，逐字符扫描。
 *   遇到数字字符就累积到 num 中；
 *   遇到 '.' 就把当前 num 入栈，并重置 num；
 *   遇到运算符就弹出栈顶两个数，先弹出的是右操作数，后弹出的是左操作数，
 *   计算后将结果入栈；
 *   遇到 '@' 结束，最后栈顶就是答案。
 * 坑点：
 *   1. 操作数可能是多位数，必须用 num = num * 10 + (c - '0') 累积；
 *   2. 减法和除法要注意顺序：先弹出的是右操作数，后弹出的是左操作数；
 *   3. 除法是整数除法，直接使用 / 即可，C++ 整数除法会截断；
 *   4. 遇到 '.' 后一定要把 num 重置为 0，否则下一个数字会出错；
 *   5. 遇到 '@' 要 break，不要继续处理；
 *   6. 输入字符串中无空格，用 cin >> s 即可读入整行；
 *   7. 栈可以用 stack<int>，本题数据范围不大；
 *   8. 若题目允许负数，需额外处理负号，但本题通常操作数非负。
 */

#include <bits/stdc++.h>

using namespace std;

int main()
{
    string s;
    cin >> s; // 读入整个表达式，比如 "3.5.2.-*7.+@"

    stack<int> st;
    int num = 0;

    for (char c : s)
    {
        // 字符串转数字
        if (c >= '0' && c <= '9')
        {
            num = num * 10 + (c - '0');
        }
        else if (c == '.')
        {
            // 数字结束，入栈
            st.push(num);
            num = 0;
        }
        else if (c == '+' || c == '-' || c == '*' || c == '/')
        {
            // 弹出两个操作数
            int b = st.top();
            st.pop();
            int a = st.top();
            st.pop();

            int res = 0;
            if (c == '+')
                res = a + b;
            if (c == '-')
                res = a - b;
            if (c == '*')
                res = a * b;
            if (c == '/')
                res = a / b;

            // 结果入栈
            st.push(res);
        }
        else if (c == '@')
        {
            break; // 结束
        }
    }

    cout << st.top() << endl; // 栈顶就是结果

    return 0;
}